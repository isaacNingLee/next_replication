"""The 3-shot program-repair prompt from NExT (Ni et al., 2024), App. E.

The instruction text, section headers, cheatsheet delimiters and closing question
are transcribed from the paper. The three exemplars are the paper's MBPP problems
(`similar_elements`, `is_not_prime`, `heap_queue_largest`) with the paper's own
rationales and fixes. Exemplar traces are *generated by tracer.py rather than
copied*, so the trace format the model sees in the exemplars is byte-identical to
the format it sees for the real task.

Three conditions, matching the rows of the paper's Table 1:
  vanilla_trace  -- traces in the prompt, answer is the fixed code only
  cot_trace      -- traces in the prompt, answer is an NL rationale then the fix
  cot_notrace    -- no traces, answer is an NL rationale then the fix
"""

import tracer

CONDITIONS = ("vanilla_trace", "cot_trace", "cot_notrace")

INSTRUCTION = (
    "We are doing pair programming, I will give you the problem definition and my "
    "implementation, which does not pass all test cases. And you need to help me to "
    "fix my code."
)

CHEATSHEET_PREAMBLE = (
    "Here is a *cheatsheet* for the gold execution trace for each assertions, use the "
    "information here but pretend you did all the reasoning about execution yourself."
)
CHEATSHEET_START = "#################### cheatsheet starts ####################"
CHEATSHEET_END = "#################### cheatsheet ends ####################"

ASK_COT = (
    "Given the above information, can you tell me why my code is wrong, and also "
    "provide a fixed version?"
)
ASK_VANILLA = "Given the above information, can you provide a fixed version?"


