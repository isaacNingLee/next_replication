def render_problem(spec, program, tests, trace_text=None, use_cot=True):
    """Render the user-side half of one turn (exemplar or real task)."""
    parts = [
        "Here is the specification in natural language and the program that I wrote:",
        f"```\n{spec}\n{program}\n\n```",
        "Here are the assertions I need to pass:",
        "```\n" + "\n".join(tests) + "\n```",
    ]
    if trace_text is not None:
        parts += [
            "",
            CHEATSHEET_PREAMBLE,
            "",
            CHEATSHEET_START,
            trace_text,
            CHEATSHEET_END,
        ]
    parts += ["", ASK_COT if use_cot else ASK_VANILLA]
    return "\n".join(parts)


def render_answer(exemplar, use_cot=True):
    body = f"{exemplar['rationale']}\n\nHere is the corrected code:\n" if use_cot else ""
    return f"{body}```\n{exemplar['fix']}\n```"


def build_fewshot_block(condition):
    """The 3 exemplars, rendered once per condition. Stable across all tasks, so
    this is exactly the span worth marking for prompt caching."""
    use_cot = condition != "vanilla_trace"
    use_trace = condition != "cot_notrace"

    chunks = [INSTRUCTION]
    for idx, ex in enumerate(EXEMPLARS, start=1):
        trace_text = None
        if use_trace:
            trace_text, _ = tracer.trace_all(ex["program"], ex["tests"])
        chunks.append(f"# Example {idx}")
        chunks.append(render_problem(ex["spec"], ex["program"], ex["tests"],
                                     trace_text, use_cot))
        chunks.append(render_answer(ex, use_cot))
    return "\n\n".join(chunks)


_TASK_PROMPT_CACHE = {}


def build_task_prompt(record, condition):
    """Render the target repair task in the same shape as the exemplars.

    Memoised: tracing actually executes the buggy program, which is the slowest
    step in the pipeline, and the same (task, condition) prompt is reused for
    every model in the roster.
    """
    cache_key = (record["task_id"], condition)
    if cache_key in _TASK_PROMPT_CACHE:
        return _TASK_PROMPT_CACHE[cache_key]

    use_cot = condition != "vanilla_trace"
    use_trace = condition != "cot_notrace"

    # Traces are precomputed by build_dataset.py; falling back to live tracing
    # keeps the module usable standalone (e.g. for the exemplars).
    trace_text = None
    if use_trace:
        trace_text = record.get("trace_text")
        if trace_text is None:
            trace_text, _ = tracer.trace_all(record["buggy_program"], record["open_tests"])

    spec = f"# Fix the bug in `{record['entry_point']}`."
    rendered = render_problem(spec, record["buggy_program"], record["open_tests"],
                              trace_text, use_cot)
    _TASK_PROMPT_CACHE[cache_key] = rendered
    return rendered


def build_messages(record, condition):
    """Return (system_block, user_block). The system block is condition-level and
    identical across all 164 tasks; the user block is task-specific."""
    return build_fewshot_block(condition), build_task_prompt(record, condition)
